def run_preseason_validation() -> dict:
    """Structural validation of the 2026-27 preseason prior (Model E)."""
    from research.preseason import (
        build_preseason_prior,
        run_preseason_baseline,
        validate_preseason_prior,
    )

    prior = build_preseason_prior()
    checks = validate_preseason_prior(prior)
    baseline = run_preseason_baseline()
    report = {
        "checks": checks,
        "n_players": len(prior),
        "gw1_baseline_rows": len(baseline),
        "top_gw1_xpts": baseline.sort_values("predicted_points", ascending=False)[
            ["web_name", "position", "predicted_points"]
        ]
        .head(10)
        .to_dict("records"),
    }
    report_path = rconfig.RESULTS_DIR / "preseason_gw1_baseline.csv"
    baseline.to_csv(report_path, index=False)
    return report
