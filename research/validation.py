# Metrics
# ---------------------------------------------------------------------------


def evaluate_outcome(
    out: pd.DataFrame,
    pred_col: str = "predicted_points",
    actual_col: str = "actual_points",
) -> pd.DataFrame:
    """Row-level (season, round, player) outcome frame with error columns."""
    df = out.dropna(subset=[pred_col, actual_col]).copy()
    df["points_error"] = df[pred_col] - df[actual_col]
    df["points_abs_error"] = df["points_error"].abs()
    df["minutes_error"] = df["expected_minutes"] - df["actual_minutes"]
    df["minutes_abs_error"] = df["minutes_error"].abs()
    df["predicted_start"] = (df["start_probability"] >= 0.5).astype(int)
    df["actual_start"] = df["actual_starts"].astype(int)
    df["is_non_starter"] = df["actual_start"] == 0
    df["actual_sub_appearance"] = (
        (df["actual_starts"] == 0) & (df["actual_minutes"] > 0)
    ).astype(int)
    df["sub_rate_error"] = df["sub_rate_given_not_start"] - df["actual_sub_appearance"]
    return df


def summarize_model(
    out: pd.DataFrame,
    pred_col: str = "predicted_points",
    actual_col: str = "actual_points",
) -> dict:
    """Aggregate metrics for one model's pooled fold output."""
    df = evaluate_outcome(out, pred_col, actual_col)
    s = {}
    s["n_predictions"] = len(df)
    if df.empty:
        return s
    s["mae_points"] = float(df["points_abs_error"].mean())
    s["rmse_points"] = float(np.sqrt((df["points_error"] ** 2).mean()))
    s["bias_points"] = float(df["points_error"].mean())
    s["corr_points"] = float(df[pred_col].corr(df[actual_col]))
    s["mae_minutes"] = float(df["minutes_abs_error"].mean())
    s["minutes_mae_faithful"] = float(df["minutes_abs_error"].mean())
    s["start_accuracy"] = float((df["predicted_start"] == df["actual_start"]).mean())
    ns = df[df["is_non_starter"]]
    if not ns.empty:
        s["sub_rate_mae"] = float(ns["sub_rate_error"].abs().mean())
        s["sub_rate_bias"] = float(ns["sub_rate_error"].mean())
        s["n_non_starters"] = len(ns)
    # Top-10 hit rate: predicted top-10 vs actual top-10 by points per gameweek.
    overlaps = []
    for (season, gw), g in df.groupby(["season", "round"]):
        pred_top = set(g.sort_values(pred_col, ascending=False).head(10)["player_id"])
        act_top = set(g.sort_values(actual_col, ascending=False).head(10)["player_id"])
        overlaps.append(len(pred_top & act_top))
    s["top10_overlap_mean"] = float(np.mean(overlaps)) if overlaps else float("nan")
    return s


def build_ablation_table(results: dict[str, dict[str, pd.DataFrame]]) -> pd.DataFrame:
    """Comparison table: fold x model x metrics."""
    rows = []
    for fold_name, models in results.items():
        for model_id, df in models.items():
            row = {
                "fold": fold_name,
                "model": model_id,
                "desc": MODELS[model_id]["desc"],
            }
            row.update(summarize_model(df))
            rows.append(row)
    return pd.DataFrame(rows)


def save_ablation(results: dict[str, dict[str, pd.DataFrame]]) -> pd.DataFrame:
    table = build_ablation_table(results)
    rconfig.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    table.to_csv(rconfig.RESULTS_DIR / "ablation_summary.csv", index=False)
    return table


