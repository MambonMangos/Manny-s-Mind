def get_candidate(candidate_id: str) -> dict:
    """Return a candidate definition by model_id (raises KeyError if absent)."""
    try:
        return CANDIDATES[candidate_id]
    except KeyError:
        raise KeyError(
            f"unknown shadow candidate {candidate_id!r}; available: {sorted(CANDIDATES)}"
        ) from None


def get_shadow_candidate() -> dict:
    """Return the primary (strongest) shadow candidate."""
    return CANDIDATES["v3_hist_d_team"]


def register_shadow_candidate(candidate_id: str | None = None) -> Path:
    """Write the candidate record with live ablation metrics to the results dir.

    ``candidate_id`` defaults to the strongest candidate (v3_hist_d_team).
    """
    cid = candidate_id or "v3_hist_d_team"
    candidate = dict(get_candidate(cid))

    metrics = {}
    try:
        table = pd.read_csv(rconfig.RESULTS_DIR / "ablation_summary.csv")
        for _, row in table[table["model"] == candidate["ablation_model"]].iterrows():
            metrics[row["fold"]] = {
                "mae_points": row["mae_points"],
                "rmse_points": row["rmse_points"],
                "bias_points": row["bias_points"],
                "corr_points": row["corr_points"],
                "mae_minutes": row["mae_minutes"],
                "start_accuracy": row["start_accuracy"],
                "top10_overlap_mean": row["top10_overlap_mean"],
            }
    except (FileNotFoundError, KeyError):
        logger.warning("ablation metrics unavailable; registering candidate without metrics")

    candidate["walk_forward_metrics"] = metrics
    path = rconfig.RESULTS_DIR / "shadow_candidate.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(candidate, f, indent=2)
    logger.info("registered shadow candidate %s -> %s", cid, path)
    return path


def load_shadow_candidate() -> dict:
    """Read the registered shadow-candidate record."""
    path = rconfig.RESULTS_DIR / "shadow_candidate.json"
    if not path.exists():
        raise FileNotFoundError("no shadow candidate registered yet; run register_shadow_candidate()")
    with open(path) as f:
        return json.load(f)
