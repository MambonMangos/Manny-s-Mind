"""Shadow candidate registry — Phase 7 of the historical-data program.

The strongest validated model is registered here as a *versioned shadow
candidate*. It is deliberately NOT wired into ``config/active.yaml`` or
``config/production/production_v1.yaml`` — promotion requires (a) real-world
head-to-head evidence from a shadow run against the production primary, and
(b) an explicit decision. The registry is the single record of what the
candidate is, why it was selected, and what promotion requires.

Candidates use the versioned experimental configs generated by
``research.calibration`` (expected_points_v1_hist / expected_minutes_v1_hist)
which never appear in the active version map, so production behaviour is
unchanged until a promotion decision is made.
"""

